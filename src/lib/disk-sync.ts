import { CourseLibraryState, LessonNote } from '@/types/course';

export const SIDECAR_FILENAME = '.courseplex-state.json';
export const CURRENT_STATE_VERSION = 1;

export function createDefaultLibraryState(): CourseLibraryState {
  return {
    version: CURRENT_STATE_VERSION,
    lastSyncedAt: new Date().toISOString(),
    clusters: {},
    courses: {},
    progress: {},
    notes: {},
    studySessions: [],
    dailyGoalMinutes: 45,
  };
}

export async function readStateFromDisk(
  rootHandle: FileSystemDirectoryHandle
): Promise<CourseLibraryState | null> {
  try {
    const fileHandle = await rootHandle.getFileHandle(SIDECAR_FILENAME, { create: false });
    const file = await fileHandle.getFile();
    const text = await file.text();
    const parsed = JSON.parse(text) as CourseLibraryState;
    if (parsed && typeof parsed === 'object') {
      return {
        ...createDefaultLibraryState(),
        ...parsed,
      };
    }
    return null;
  } catch {
    return null; // Sidecar file does not exist yet on fresh directory
  }
}

export async function writeStateToDisk(
  rootHandle: FileSystemDirectoryHandle,
  state: CourseLibraryState
): Promise<void> {
  try {
    const fileHandle = await rootHandle.getFileHandle(SIDECAR_FILENAME, { create: true });
    const writable = await (fileHandle as unknown as { createWritable: () => Promise<FileSystemWritableFileStream> }).createWritable();
    const payload: CourseLibraryState = {
      ...state,
      lastSyncedAt: new Date().toISOString(),
    };
    await writable.write(JSON.stringify(payload, null, 2));
    await writable.close();
  } catch (err) {
    console.error('Failed to write state to disk sidecar:', err);
    throw err;
  }
}

export async function writeCourseNotesToDisk(
  courseDirHandle: FileSystemDirectoryHandle,
  notes: LessonNote[],
  courseTitle: string
): Promise<string> {
  const fileName = 'COURSE_NOTES.md';
  const fileHandle = await courseDirHandle.getFileHandle(fileName, { create: true });
  const writable = await (fileHandle as unknown as { createWritable: () => Promise<FileSystemWritableFileStream> }).createWritable();

  // Sort notes by lesson then timestamp
  const sortedNotes = [...notes].sort((a, b) => {
    if (a.lessonPath === b.lessonPath) {
      return a.timestampSeconds - b.timestampSeconds;
    }
    return a.lessonPath.localeCompare(b.lessonPath);
  });

  const lines: string[] = [
    `# Course Notes: ${courseTitle}`,
    `*Generated by CoursePlex on ${new Date().toLocaleDateString()} at ${new Date().toLocaleTimeString()}*`,
    `\n---\n`,
  ];

  let currentLesson = '';
  for (const note of sortedNotes) {
    if (note.lessonPath !== currentLesson) {
      currentLesson = note.lessonPath;
      lines.push(`\n## Lesson: ${note.lessonPath}\n`);
    }

    const minutes = Math.floor(note.timestampSeconds / 60);
    const seconds = Math.floor(note.timestampSeconds % 60);
    const timeFormatted = `${String(minutes).padStart(2, '0')}:${String(seconds).padStart(2, '0')}`;

    const tagsStr = note.tags && note.tags.length > 0 ? ` ${note.tags.map(t => `#${t}`).join(' ')}` : '';
    lines.push(`### [${timeFormatted}]${tagsStr}`);
    lines.push(note.contentMarkdown.trim());
    lines.push('');
  }

  const content = lines.join('\n');
  await writable.write(content);
  await writable.close();
  return fileName;
}

export function downloadBackupJson(state: CourseLibraryState): void {
  const blob = new Blob([JSON.stringify(state, null, 2)], { type: 'application/json' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `courseplex-backup-${new Date().toISOString().slice(0, 10)}.json`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
